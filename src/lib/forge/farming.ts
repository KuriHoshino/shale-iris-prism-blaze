/** Average produce is 4.5. Premium doubles it. A matching island adds 10% to produce only. */
export function produceEach(premium: boolean, islandBonus: boolean) {
  return 4.5 * (premium ? 2 : 1) * (islandBonus ? 1.1 : 1)
}

export function farmProfit(
  row: FarmRow,
  count: number,
  premium: boolean,
  islandBonus: boolean,
  seedPrice: number,
  productPrice: number,
  wormPrice: number,
  focusEach: number,
) {
  const plants = Math.max(1, Math.floor(count))
  const grown = produceEach(premium, islandBonus)
  const watered = row.baseYield + row.careBonus * row.actions
  const unwateredReplace = seedPrice * Math.max(0, 1 - row.baseYield)
  const wateredShort = Math.max(0, 1 - watered)
  const surplus = Math.max(0, watered - 1)
  const worms = 0.1 * wormPrice
  const crop = grown * productPrice
  const unwateredEach = crop + worms - unwateredReplace
  const wateredEach = crop + worms + surplus * seedPrice - seedPrice * wateredShort
  const gain = wateredEach - unwateredEach
  return {
    grown,
    watered,
    unwateredReplace,
    surplus,
    unwateredEach,
    wateredEach,
    unwateredPlot: unwateredEach * plants,
    wateredPlot: wateredEach * plants,
    perFocus: focusEach > 0 ? gain / focusEach : 0,
  }
}

export function islandCities(id: string) {
  return ISLAND_BONUS[id] ?? []
}

export function farmFocusCost(farming: number, spec: number) {
  const general = Math.max(0, Math.min(100, farming))
  const special = Math.max(0, Math.min(100, spec))
  return Math.round(1000 * Math.pow(0.5, (general + special * 2) / 100))
}

export function farmPlan(
  row: FarmRow,
  count: number,
  farming: number,
  spec: number,
  premium: boolean,
  useFavorite: boolean,
  city: IslandCity | "",
) {
  const safe = Math.max(1, Math.floor(count))
  const eachFocus = farmFocusCost(farming, spec)
  const waterings = row.group === "breed" ? 0 : safe
  const nurtures = row.group === "breed" ? safe * row.actions : 0
  const focus = (waterings + nurtures) * eachFocus
  const growthHours = row.growHours
  const cities = islandCities(row.id)
  const islandBonus = city && cities.includes(city) ? 0.1 : 0
  const bare = row.baseYield
  const full = row.baseYield + row.careBonus * row.actions
  let food: { name: string; each: number; total: number; feedings: number; guide: number | null } | null = null
  if (row.nutritionMax > 0 && row.secondsPerNutrition > 0 && row.food) {
    const base = FOOD_NUTRITION[row.food]
    const favored = useFavorite && row.favoriteBonus > 0 && row.favoriteName
    const nutrition = base.nutrition * (favored ? 1 + row.favoriteBonus : 1)
    const growSeconds = growthHours * 3600
    const points = growSeconds / row.secondsPerNutrition
    const each = Math.max(1, Math.round(row.nutritionMax / nutrition))
    const one = Math.max(1, Math.round(points / nutrition))
    const total = one * safe
    const feedings = points / row.nutritionMax
    const guide = row.food === "meat" ? Math.round(points / 48) : null
    food = { name: favored ? row.favoriteName : base.name, each, total, feedings, guide }
  }
  const harvestEach = row.group === "breed" ? 0 : 4.5 * (premium ? 2 : 1) * (1 + islandBonus)
  return {
    eachFocus,
    waterings,
    nurtures,
    focus,
    food,
    growthHours,
    bare,
    full,
    expected: full * safe,
    cities,
    islandBonus,
    harvest: harvestEach * safe,
  }
}
